#!/usr/bin/env node
// Writes `app/lib/version.js`, which the footer reads.
//
// Generated rather than computed in the loader, and the reason is the deploy.
// This site is a Cloudflare Worker, so everything a loader imports ends up in a
// bundle workerd loads, and workerd has no `node:fs`. Reading a manifest and
// asking git are both Node, so they happen here and leave plain constants
// behind.
//
// A build passes without this. `wrangler deploy` is the only thing that would
// have caught it, which it did, in CI, after the merge.

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

// www/scripts -> www -> the repository.
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const out = path.join(here, '../app/lib/version.js');

const git = (...args) =>
  execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();

const { version } = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

/**
 * Whether this build is the commit `bin/release.js` tagged for that version.
 *
 * Not knowing counts as ahead. The way to not know is a checkout with no tags,
 * and being wrong that way only says the pages may run ahead of the release.
 * Wrong the other way is the site claiming to document something you can
 * install when it does not.
 */
let released = false;
try {
  released = git('rev-parse', '--verify', `v${version}^{commit}`) === git('rev-parse', 'HEAD');
} catch {
  released = false;
}

const RELEASES = 'https://github.com/transclude-dev/transclude/releases';

fs.writeFileSync(
  out,
  `// Generated by scripts/write-version.js. Do not edit.
//
// Plain constants on purpose: a loader importing this ends up in the worker
// bundle, and workerd has no \`node:fs\` to read a manifest with.

/** The version both packages carry. */
export const version = ${JSON.stringify(version)};

/** Whether this build is the commit tagged for it. */
export const released = ${released};

/** Where the footer's version links: the release, or the list of them. */
export const versionHref = ${JSON.stringify(released ? `${RELEASES}/tag/v${version}` : RELEASES)};

/** \`v${version}\`, or \`after v${version}\` when the pages describe more than it. */
export const versionLabel = ${JSON.stringify(released ? `v${version}` : `after v${version}`)};
`,
);

process.stdout.write(`app/lib/version.js: ${released ? `v${version}` : `after v${version}`}\n`);
